"""Generate a commit index for benchmark result files.

Usage:
    python scripts/results_readme.py
    python scripts/results_readme.py --results results/ --out results/COMMITS.md

Each `results/<sha>.json` file becomes one row with the commit, its subject,
and a relative link to the result file. Rows already present in the index are
reused, so a run only looks up commits it has not seen. Rows are sorted by the
first-parent position recorded in each result file, which is Numba's linear
history order.

Commit subjects are read from a local Numba checkout when available and from
the GitHub API otherwise. Pass `--offline` to skip the API fallback.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

SHA_RE = re.compile(r"[0-9a-f]{40}")
ROW_RE = re.compile(r"^\|\s*\[`([0-9a-f]{40})`\]")
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_NUMBA_REPO = ROOT.parent / "numba"
SCRIPT_URL = (
    "https://github.com/numba/numba-benchmark/blob/main/scripts/results_readme.py"
)


def document_order(document):
    """Numba's linear history order, via first-parent position."""
    position = document.get("position")
    if position is None:
        return (1, 0, document.get("date", ""), document["commit"])
    return (0, position, document.get("date", ""), document["commit"])


def load_result_files(directory):
    documents = []
    directory = Path(directory)
    if not directory.is_dir():
        return documents
    for path in sorted(directory.rglob("*.json")):
        if not SHA_RE.fullmatch(path.stem):
            continue
        try:
            document = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if document.get("commit") != path.stem or "measurements" not in document:
            continue
        documents.append((path, document))
    documents.sort(key=lambda item: document_order(item[1]))
    return documents


def git_subject(repo, sha):
    if not repo:
        return None
    try:
        completed = subprocess.run(
            ["git", "-C", str(repo), "show", "-s", "--format=%s", sha],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    subject = completed.stdout.strip().splitlines()
    return subject[0].strip() if subject else None


def github_subject(repository, sha, timeout):
    request = urllib.request.Request(
        f"https://api.github.com/repos/{repository}/commits/{sha}",
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "numba-benchmark-results-readme",
        },
    )
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            document = json.load(response)
    except (OSError, urllib.error.URLError, json.JSONDecodeError):
        return None
    message = document.get("commit", {}).get("message", "")
    subject = message.splitlines()
    return subject[0].strip() if subject else None


def commit_subject(document, args):
    sha = document["commit"]
    subject = git_subject(args.numba_repo, sha)
    if subject or args.offline:
        return subject or "(unavailable)"
    subject = github_subject(args.github_repo, sha, args.timeout)
    return subject or "(unavailable)"


def markdown_cell(text):
    return " ".join(str(text).split()).replace("|", r"\|")


def relative_link(path, start):
    relative = Path(os.path.relpath(path, start)).as_posix()
    if not relative.startswith((".", "/")):
        relative = f"./{relative}"
    return relative


def load_existing_rows(path):
    """Map commit SHA to its existing table row so it is not regenerated."""
    try:
        text = Path(path).read_text()
    except OSError:
        return {}
    rows = {}
    for line in text.splitlines():
        match = ROW_RE.match(line)
        if match:
            rows[match.group(1)] = line
    return rows


def generate_readme(result_files, out_path, args):
    out_path = Path(out_path)
    existing_rows = load_existing_rows(out_path)
    lines = [
        "# Benchmark results",
        "",
        "One JSON file per Numba commit, generated by the benchmark CI. This "
        f"table is generated by [`scripts/results_readme.py`]({SCRIPT_URL}); "
        "do not edit it by hand.",
        "",
        "Refresh it from the `numba-benchmark` repository root with:",
        "",
        "```bash",
        "python scripts/results_readme.py",
        "```",
        "",
        "| Commit | Message | Results |",
        "|---|---|---|",
    ]
    added = 0
    for path, document in result_files:
        sha = document["commit"]
        row = existing_rows.get(sha)
        if row is None:
            commit_url = f"https://github.com/{args.github_repo}/commit/{sha}"
            commit = f"[`{sha}`]({commit_url})"
            message = markdown_cell(commit_subject(document, args))
            results = f"[{sha[:12]}.json]({relative_link(path, out_path.parent)})"
            row = f"| {commit} | {message} | {results} |"
            added += 1
        lines.append(row)
    lines.append("")
    return "\n".join(lines), added


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="results/", help="result JSON directory")
    parser.add_argument(
        "--out", default="results/COMMITS.md", help="index path to write"
    )
    parser.add_argument(
        "--numba-repo",
        default=str(DEFAULT_NUMBA_REPO),
        help="local Numba checkout used for commit subjects",
    )
    parser.add_argument(
        "--github-repo",
        default="numba/numba",
        help="GitHub repository for commit links and API fallback",
    )
    parser.add_argument(
        "--timeout", type=float, default=10, help="GitHub API timeout in seconds"
    )
    parser.add_argument(
        "--offline",
        action="store_true",
        help="do not query the GitHub API for missing commit subjects",
    )
    args = parser.parse_args(argv)

    result_files = load_result_files(args.results)
    if not result_files:
        print(f"no result files found in {args.results}", file=sys.stderr)
        return

    out_path = Path(args.out)
    old_text = out_path.read_text() if out_path.is_file() else ""
    text, added = generate_readme(result_files, out_path, args)
    if text == old_text:
        print(f"{out_path} is up to date ({len(result_files)} commit(s))", file=sys.stderr)
        return
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text)
    print(
        f"wrote {out_path} ({added} new, {len(result_files)} commit(s))",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
